import type { Casing } from "drizzle-orm";
import { diffSnapshots, idempotentStatements } from "./diff.js";
import type { PgExtras } from "./defs.js";
import { PgExtrasError } from "./errors.js";
import {
  extrasSnapshotPath,
  joinStatements,
  readExtrasSnapshotFile,
  sanitizeMigrationName,
  writeMigration,
  type MigrationPrefix,
  type WrittenMigration,
} from "./journal.js";
import { emptySnapshot, parseSnapshot, snapshotExtras, type Snapshot } from "./snapshot.js";
import { VERSION } from "./version.js";

export type GenerateOptions = {
  extras: PgExtras;
  out: string;
  name?: string;
  casing?: Casing;
  prefix?: MigrationPrefix;
  breakpoints?: boolean;
};

export type GenerateResult =
  | { written: false; up: string[]; down: string[] }
  | ({
      written: true;
      up: string[];
      down: string[];
    } & WrittenMigration);

const UP_HEADER = `-- Generated by drizzle-pg-extras ${VERSION}. Review before applying.`;
const DOWN_HEADER = `-- Down SQL for drizzle-pg-extras ${VERSION}. drizzle-kit migrate does not run this file.`;

export function loadStoredSnapshot(out: string): Snapshot {
  const raw = readExtrasSnapshotFile(out);
  if (raw === null) return emptySnapshot();
  try {
    return parseSnapshot(raw);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new PgExtrasError(`${extrasSnapshotPath(out)}: ${message}`);
  }
}

export function planExtras(extras: PgExtras, previous: Snapshot, casing?: Casing) {
  const next = snapshotExtras(extras, casing ? { casing } : undefined);
  const diff = diffSnapshots(previous, next);
  return { next, ...diff };
}

export function generate(options: GenerateOptions): GenerateResult {
  const name = sanitizeMigrationName(options.name ?? "pg_extras");
  const previous = loadStoredSnapshot(options.out);
  const planned = planExtras(options.extras, previous, options.casing);
  if (planned.up.length === 0) {
    return { written: false, up: [], down: [] };
  }
  const breakpoints = options.breakpoints ?? true;
  const written = writeMigration({
    out: options.out,
    name,
    up: joinStatements(planned.up, breakpoints, UP_HEADER),
    down: joinStatements(planned.down, breakpoints, DOWN_HEADER),
    snapshot: planned.next,
    prefix: options.prefix,
    breakpoints,
  });
  return { written: true, up: planned.up, down: planned.down, ...written };
}

export function pendingStatements(extras: PgExtras, out: string, casing?: Casing): string[] {
  return planExtras(extras, loadStoredSnapshot(out), casing).up;
}

export function renderIdempotent(extras: PgExtras, options?: { casing?: Casing; breakpoints?: boolean }): string {
  const snapshot = snapshotExtras(extras, options?.casing ? { casing: options.casing } : undefined);
  return joinStatements(idempotentStatements(snapshot), options?.breakpoints ?? true, UP_HEADER);
}

export { idempotentStatements };
