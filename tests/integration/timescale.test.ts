import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { integer, pgTable, timestamp } from "drizzle-orm/pg-core";
import pg from "pg";
import { describe, expect, it } from "vitest";
import { run } from "../../src/cli.js";
import { splitMigrationSql } from "../../src/journal.js";
import { createHypertableSql, defineExtras, hypertable, pgExtension, snapshotExtras } from "../../src/index.js";

const url = process.env.TIMESCALE_URL;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../.tmp");
const kit = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../node_modules/drizzle-kit/bin.cjs");
const source = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../src/index.ts");

describe.skipIf(!url)("timescaledb hypertables", () => {
  it("migrates a hypertable through drizzle-kit and leaves no schema diff", async () => {
    mkdirSync(root, { recursive: true });
    const dir = mkdtempSync(path.join(root, "ts-"));
    writeFileSync(path.join(dir, "schema.ts"), schemaSource(source));
    writeFileSync(path.join(dir, "drizzle.config.ts"), configSource());

    const client = new pg.Client({ connectionString: url });
    await client.connect();
    const cwd = process.cwd();
    try {
      await reset(client);
      const table = kitExec(dir, ["generate", "--name", "metrics", "--config", "drizzle.config.ts"]);
      expect(table.status, table.stderr + table.stdout).toBe(0);

      process.chdir(dir);
      expect(await run(["generate", "--name", "hypertables"])).toBe(0);
      process.chdir(cwd);

      const migrate = kitExec(dir, ["migrate", "--config", "drizzle.config.ts"]);
      expect(migrate.status, migrate.stderr + migrate.stdout).toBe(0);

      const upPath = path.join(dir, "drizzle", "0001_hypertables.sql");
      const upSql = readFileSync(upPath, "utf8");
      expect(upSql).toContain('CREATE EXTENSION IF NOT EXISTS "timescaledb"');
      expect(upSql.indexOf("CREATE EXTENSION")).toBeLessThan(upSql.indexOf("create_hypertable"));
      expect(upSql).toContain("if_not_exists => TRUE");
      expect(upSql).toContain(`chunk_time_interval => INTERVAL '1 day'`);
      expect(upSql).toContain("number_partitions => 4");
      expect(upSql).toContain("add_retention_policy");
      expect(upSql).toContain("add_compression_policy");
      expect(upSql).toContain("Generated by drizzle-pg-extras 0.5.0");
      await runStatements(client, upSql);

      expect(await intervalEquals(client, "public", "metrics", "time", "1 day")).toBe(true);
      expect(await partitionsOf(client, "public", "metrics", "device_id")).toBe(4);
      expect(await intervalEquals(client, "market", "readings", "time", "1 hour")).toBe(true);
      expect(await compressionEnabled(client, "public", "metrics")).toBe(true);
      const order = await client.query<{ attname: string; orderby_asc: boolean | null }>(
        `SELECT attname, orderby_asc FROM timescaledb_information.compression_settings
         WHERE hypertable_schema = 'public' AND hypertable_name = 'metrics' ORDER BY attname`,
      );
      expect(order.rows).toEqual([
        { attname: "device_id", orderby_asc: null },
        { attname: "time", orderby_asc: false },
      ]);
      expect(await policyInterval(client, "metrics", "policy_retention", "drop_after", "6 months")).toBe(true);
      expect(await policyInterval(client, "metrics", "policy_compression", "compress_after", "7 days")).toBe(true);
      const schedule = await client.query<{ matches: boolean }>(
        `SELECT schedule_interval = INTERVAL '1 day' AS matches
         FROM timescaledb_information.jobs
         WHERE hypertable_name = 'metrics' AND proc_name = 'policy_retention'`,
      );
      expect(schedule.rows[0]?.matches).toBe(true);

      await client.query(`INSERT INTO metrics (time, device_id, value) VALUES ('2024-06-01', 'device-a', 1)`);
      const inserted = await client.query<{ chunks: string }>(
        `SELECT count(*)::text AS chunks FROM timescaledb_information.chunks
         WHERE hypertable_schema = 'public' AND hypertable_name = 'metrics'`,
      );
      expect(Number(inserted.rows[0]?.chunks)).toBeGreaterThan(0);

      const before = sqlFiles(path.join(dir, "drizzle"));
      const again = kitExec(dir, ["generate", "--name", "noop", "--config", "drizzle.config.ts"]);
      expect(again.status, again.stderr + again.stdout).toBe(0);
      expect(again.stdout).toContain("No schema changes");
      expect(sqlFiles(path.join(dir, "drizzle"))).toEqual(before);

      process.chdir(dir);
      expect(await run(["generate", "--name", "again"])).toBe(0);
      process.chdir(cwd);
      expect(sqlFiles(path.join(dir, "drizzle"))).toEqual(before);

      writeFileSync(path.join(dir, "schema.ts"), schemaSource(source, { chunk: "2 days", dropAfter: "3 months", direction: "asc" }));
      process.chdir(dir);
      expect(await run(["generate", "--name", "chunk_interval"])).toBe(0);
      process.chdir(cwd);
      const follow = kitExec(dir, ["migrate", "--config", "drizzle.config.ts"]);
      expect(follow.status, follow.stderr + follow.stdout).toBe(0);
      const changedSql = readFileSync(path.join(dir, "drizzle", "0002_chunk_interval.sql"), "utf8");
      expect(changedSql).toContain("set_chunk_time_interval");
      expect(changedSql).toContain("INTERVAL '2 days'");
      expect(changedSql).toContain("INTERVAL '3 months'");
      expect(changedSql).not.toContain("create_hypertable");
      await runStatements(client, changedSql);

      expect(await intervalEquals(client, "public", "metrics", "time", "2 days")).toBe(true);
      expect(await policyInterval(client, "metrics", "policy_retention", "drop_after", "3 months")).toBe(true);
      const asc = await client.query<{ orderby_asc: boolean }>(
        `SELECT orderby_asc FROM timescaledb_information.compression_settings
         WHERE hypertable_schema = 'public' AND hypertable_name = 'metrics' AND attname = 'time'`,
      );
      expect(asc.rows[0]?.orderby_asc).toBe(true);

      await runStatements(client, readFileSync(path.join(dir, "drizzle", "0002_chunk_interval.down.sql"), "utf8"));
      expect(await intervalEquals(client, "public", "metrics", "time", "1 day")).toBe(true);
      expect(await policyInterval(client, "metrics", "policy_retention", "drop_after", "6 months")).toBe(true);
      const desc = await client.query<{ orderby_asc: boolean }>(
        `SELECT orderby_asc FROM timescaledb_information.compression_settings
         WHERE hypertable_schema = 'public' AND hypertable_name = 'metrics' AND attname = 'time'`,
      );
      expect(desc.rows[0]?.orderby_asc).toBe(false);

      await runStatements(client, readFileSync(path.join(dir, "drizzle", "0001_hypertables.down.sql"), "utf8"));
      expect(await compressionEnabled(client, "public", "metrics")).toBe(false);
      const jobs = await client.query(`SELECT 1 FROM timescaledb_information.jobs WHERE hypertable_name = 'metrics'`);
      expect(jobs.rowCount).toBe(0);
      const still = await client.query(
        `SELECT 1 FROM timescaledb_information.hypertables
         WHERE hypertable_schema = 'public' AND hypertable_name = 'metrics'`,
      );
      expect(still.rowCount).toBe(1);
      const extension = await client.query(`SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'`);
      expect(extension.rowCount).toBe(1);

      const finalKit = kitExec(dir, ["generate", "--name", "still_noop", "--config", "drizzle.config.ts"]);
      expect(finalKit.status, finalKit.stderr + finalKit.stdout).toBe(0);
      expect(finalKit.stdout).toContain("No schema changes");
    } finally {
      process.chdir(cwd);
      await client.end();
    }
  });

  it("refuses a non-empty table unless migrateData is set", async () => {
    const client = new pg.Client({ connectionString: url });
    await client.connect();
    try {
      await reset(client);
      await client.query(`CREATE EXTENSION IF NOT EXISTS timescaledb`);
      await client.query(`
        CREATE TABLE occupied (
          "time" timestamp with time zone NOT NULL,
          "value" integer NOT NULL
        )
      `);
      await client.query(`INSERT INTO occupied ("time", "value") VALUES ('2024-06-01', 1)`);
      await expect(client.query(hypertableSql(false))).rejects.toThrow(/not empty/);
      const moved = hypertableSql(true);
      await client.query(moved);
      await client.query(moved);
      const count = await client.query<{ count: string }>(`SELECT count(*)::text AS count FROM occupied`);
      expect(count.rows[0]?.count).toBe("1");
      const kind = await client.query(
        `SELECT 1 FROM timescaledb_information.hypertables WHERE hypertable_schema = 'public' AND hypertable_name = 'occupied'`,
      );
      expect(kind.rowCount).toBe(1);
    } finally {
      await client.end();
    }
  });
});

function hypertableSql(migrateData: boolean): string {
  const occupied = pgTable("occupied", {
    time: timestamp("time", { withTimezone: true }).notNull(),
    value: integer("value").notNull(),
  });
  const snap = snapshotExtras(defineExtras({
    extensions: [pgExtension("timescaledb")],
    hypertables: [hypertable(occupied, { timeColumn: occupied.time, chunkTimeInterval: "1 day", migrateData })],
  }));
  return createHypertableSql(snap.hypertables[0]!);
}

function schemaSource(sourcePath: string, options?: { chunk?: string; dropAfter?: string; direction?: string }): string {
  const chunk = options?.chunk ?? "1 day";
  const dropAfter = options?.dropAfter ?? "6 months";
  const direction = options?.direction ?? "desc";
  return `import { integer, pgSchema, pgTable, text, timestamp, primaryKey } from "drizzle-orm/pg-core";
import { hypertable, pgExtension } from ${JSON.stringify(sourcePath)};

export const timescale = pgExtension("timescaledb");

export const metrics = pgTable("metrics", {
  time: timestamp("time", { withTimezone: true }).notNull(),
  deviceId: text("device_id").notNull(),
  value: integer("value").notNull(),
}, (t) => [
  primaryKey({ columns: [t.time, t.deviceId] }),
]);

export const metricsHypertable = hypertable(metrics, {
  timeColumn: metrics.time,
  chunkTimeInterval: "${chunk}",
  partitioningColumn: metrics.deviceId,
  numberPartitions: 4,
  compression: {
    segmentBy: [metrics.deviceId],
    orderBy: [{ column: metrics.time, direction: "${direction}" }],
  },
  retention: { dropAfter: "${dropAfter}", scheduleInterval: "1 day" },
  compressionPolicy: { compressAfter: "7 days" },
});

export const market = pgSchema("market");

export const readings = market.table("readings", {
  time: timestamp("time", { withTimezone: true, precision: 3 }).notNull(),
  value: integer("value").notNull(),
});

export const readingsHypertable = hypertable(readings, {
  timeColumn: readings.time,
  chunkTimeInterval: "1 hour",
});
`;
}

function configSource(): string {
  return `import { defineConfig } from "drizzle-kit";
export default defineConfig({
  dialect: "postgresql",
  schema: "./schema.ts",
  out: "./drizzle",
  dbCredentials: { url: process.env.TIMESCALE_URL! },
});
`;
}

async function reset(client: pg.Client): Promise<void> {
  await client.query("DROP SCHEMA IF EXISTS drizzle CASCADE");
  await client.query("DROP SCHEMA IF EXISTS market CASCADE");
  await client.query("DROP TABLE IF EXISTS public.metrics CASCADE");
  await client.query("DROP TABLE IF EXISTS public.occupied CASCADE");
}

async function intervalEquals(client: pg.Client, schema: string, table: string, column: string, interval: string): Promise<boolean> {
  const result = await client.query<{ matches: boolean }>(
    `SELECT time_interval = $4::interval AS matches
     FROM timescaledb_information.dimensions
     WHERE hypertable_schema = $1 AND hypertable_name = $2 AND column_name = $3`,
    [schema, table, column, interval],
  );
  return result.rows[0]?.matches === true;
}

async function partitionsOf(client: pg.Client, schema: string, table: string, column: string): Promise<number | null> {
  const result = await client.query<{ num_partitions: number | null }>(
    `SELECT num_partitions FROM timescaledb_information.dimensions
     WHERE hypertable_schema = $1 AND hypertable_name = $2 AND column_name = $3`,
    [schema, table, column],
  );
  const value = result.rows[0]?.num_partitions;
  return value === undefined || value === null ? null : Number(value);
}

async function compressionEnabled(client: pg.Client, schema: string, table: string): Promise<boolean> {
  const result = await client.query<{ compression_enabled: boolean }>(
    `SELECT compression_enabled FROM timescaledb_information.hypertables
     WHERE hypertable_schema = $1 AND hypertable_name = $2`,
    [schema, table],
  );
  return result.rows[0]?.compression_enabled === true;
}

async function policyInterval(client: pg.Client, table: string, proc: string, key: string, interval: string): Promise<boolean> {
  const result = await client.query<{ matches: boolean }>(
    `SELECT (config->>$3)::interval = $4::interval AS matches
     FROM timescaledb_information.jobs
     WHERE hypertable_name = $1 AND proc_name = $2`,
    [table, proc, key, interval],
  );
  return result.rows[0]?.matches === true;
}

function kitExec(cwd: string, args: string[]) {
  return spawnSync(process.execPath, [kit, ...args], {
    cwd,
    encoding: "utf8",
    env: process.env,
  });
}

async function runStatements(client: pg.Client, file: string): Promise<void> {
  for (const statement of splitMigrationSql(file)) {
    await client.query(statement);
  }
}

function sqlFiles(dir: string): string[] {
  return readdirSync(dir).filter((file) => file.endsWith(".sql") && !file.endsWith(".down.sql")).sort();
}
